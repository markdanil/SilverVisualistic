    public static String effectName(String effectPath) {
        if (effectPath == null) return "";
        Map<String, String> names = PvPOverlayConfig.language == 1 ? EN_EFFECTS : RU_EFFECTS;
        return names.getOrDefault(effectPath, effectPath.replace('_', ' '));
    }

    public static String tr(String russian) {
        if (PvPOverlayConfig.language != 1) return russian;
        return EN.getOrDefault(russian, russian);
    }
